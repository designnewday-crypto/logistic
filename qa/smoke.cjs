const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const { existsSync }=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const ARTIFACTS=path.join(ROOT,'qa','screenshots');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined),headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 await fs.mkdir(ARTIFACTS,{recursive:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1,acceptDownloads:true,offline:true});
 const errors=[], posts=[], checks=[], externalRequests=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 page.on('request',r=>{if(r.method()==='POST')posts.push(r.url());if(/^https?:/.test(r.url()))externalRequests.push(r.url());});
 const check=(name,condition)=>{assert(condition,name);checks.push(name)};
 await page.setContent(await fs.readFile(path.join(ROOT,'dist','index.html'),'utf8'),{waitUntil:'networkidle'}); await page.locator('h1').waitFor();
 await page.evaluate(()=>document.fonts.ready);
 check('Main content and all generated images rendered',await page.locator('h1').innerText()==='Let’s get your\ncargo moving.' && await page.locator('img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)));
 check('Local display font loaded',await page.evaluate(()=>document.fonts.check('850 72px "Inter Variable"')));
 await page.getByRole('button',{name:'Services',exact:true}).click();
 check('Services navigation expands',await page.locator('#services-menu').isVisible());
 await page.keyboard.press('Escape');
 check('Escape closes the dropdown and restores focus',!await page.locator('#services-menu').isVisible()&&await page.locator('.dropdown-trigger').first().evaluate(e=>e===document.activeElement));
 await page.getByRole('button',{name:'Routes',exact:true}).click();
 await page.locator('#routes-menu').getByRole('link',{name:'Plan your route'}).click();
 check('Route CTA focuses collection input',await page.locator('#collection').evaluate(e=>e===document.activeElement));
 await page.getByRole('button',{name:'Request a quote',exact:true}).click();
 check('Empty form shows four required-field errors',await page.locator('.field-error:visible').count()===4);
 check('Invalid submission focuses first invalid field',await page.locator('#collection').evaluate(e=>e===document.activeElement));
 await page.getByLabel('Collection location',{exact:true}).fill('Burgas, Bulgaria');
 await page.getByLabel('Delivery location',{exact:true}).fill('Berlin, Germany');
 await page.getByLabel('Cargo type',{exact:true}).selectOption({label:'Palletised goods'});
 await page.getByLabel('Estimated weight',{exact:true}).fill('-1');
 await page.getByLabel('Work email',{exact:true}).fill('not-an-email');
 await page.getByRole('button',{name:'Request a quote',exact:true}).click();
 check('Weight and email validation reject invalid values',await page.locator('#weight').getAttribute('aria-invalid')==='true'&&await page.locator('#email').getAttribute('aria-invalid')==='true');
 await page.getByLabel('Estimated weight',{exact:true}).fill('1250');
 await page.getByLabel('Work email',{exact:true}).fill('logistics@example.com');
 await page.getByRole('button',{name:'Request a quote',exact:true}).click();
 check('Valid form opens an honest review state',await page.getByRole('dialog').isVisible()&&(await page.getByRole('dialog').innerText()).includes('No message has been sent.'));
 check('Review preserves entered route and cargo',await page.locator('[data-summary="collection"]').innerText()==='Burgas, Bulgaria'&&await page.locator('[data-summary="weight"]').innerText()==='1250 kg');
 await page.screenshot({path:path.join(ARTIFACTS,'enquiry-review.png')});
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download enquiry',exact:true}).click();
 const download=await downloadPromise;
 const file=await download.path();const text=await fs.readFile(file,'utf8');
 check('Downloaded enquiry contains the submitted fields',text.includes('Collection: Burgas, Bulgaria')&&text.includes('Delivery: Berlin, Germany')&&text.includes('1250 kg')&&text.includes('logistics@example.com'));
 check('Download filename is meaningful',download.suggestedFilename()==='burgas-logistics-enquiry.txt');
 await page.getByRole('button',{name:'Edit details',exact:true}).click();
 check('Editing returns to the form without losing entries',!await page.getByRole('dialog').isVisible()&&await page.locator('#collection').inputValue()==='Burgas, Bulgaria');
 await page.locator('.header-contact').click();
 check('Contact dialog has confirmed Burgas office information',(await page.getByRole('dialog').innerText()).includes('Burgas, Bulgaria'));
 await page.getByRole('button',{name:'Start your enquiry',exact:true}).click();
 check('Contact CTA returns to the quote form',!await page.getByRole('dialog').isVisible()&&await page.locator('#collection').evaluate(e=>e===document.activeElement));
 await page.locator('.privacy-note').getByRole('button',{name:'Privacy policy',exact:true}).click();
 check('Privacy notice explains local-only form processing',(await page.getByRole('dialog').innerText()).includes('No form data is sent to a server.'));
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Terms of Service',exact:true}).click();
 check('Terms identify the working-name website concept',(await page.getByRole('dialog').innerText()).includes('working name'));
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:390,height:844});
 await page.setContent(await fs.readFile(path.join(ROOT,'dist','index.html'),'utf8'),{waitUntil:'networkidle'}); await page.locator('h1').waitFor();
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 check('Mobile navigation opens',await page.locator('#primary-navigation').isVisible());
 await page.locator('#primary-navigation').getByRole('button',{name:'Services',exact:true}).click();
 await page.locator('#services-menu').getByRole('button',{name:/Road freight/}).click();
 check('Mobile service item opens its detail dialog',await page.getByRole('heading',{name:'A clear route by road.',exact:true}).isVisible());
 await page.getByRole('button',{name:'Plan a road shipment',exact:true}).click();
 check('Mobile service CTA closes navigation and focuses the form',!await page.getByRole('dialog').isVisible()&&await page.locator('.menu-toggle').getAttribute('aria-expanded')==='false'&&await page.locator('#collection').evaluate(e=>e===document.activeElement));
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 await page.keyboard.press('Escape');
 check('Escape closes mobile navigation',await page.locator('.menu-toggle').getAttribute('aria-expanded')==='false');
 await page.mouse.move(1,1);
 await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo({top:0,behavior:'instant'})});
 await page.screenshot({path:path.join(ARTIFACTS,'mobile-390-final.png'),fullPage:true});
 for (const width of [320,390,768,820,946,1024,1440]) {
  await page.setViewportSize({width,height:1000});
  const overflow=await page.evaluate(()=>({
   page:document.documentElement.scrollWidth>innerWidth,
   text:[...document.querySelectorAll('h1,h2,h3')].some(e=>e.clientWidth>0&&e.scrollWidth>e.clientWidth+2)
  }));
  check(`No viewport or heading overflow at ${width}px`,!overflow.page&&!overflow.text);
  if (width===946 || width===1440) await page.screenshot({path:path.join(ARTIFACTS,`desktop-${width}-final.png`),fullPage:true});
 }
 await page.setViewportSize({width:390,height:844});
 check('No page overflow at mobile width',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
 check('Form submissions do not send any network POST requests',posts.length===0);
 check('No browser console or page errors',errors.length===0);
 check('Standalone HTML does not request external resources',externalRequests.length===0);
 const report={passed:checks.length,failed:0,checks,consoleErrors:errors,networkPosts:posts};
 await fs.writeFile(path.join(ARTIFACTS,'verification-results.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
